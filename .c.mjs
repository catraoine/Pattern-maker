import { chromium } from '@playwright/test';
const OUT = process.argv[2];
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
p.on('pageerror', (e) => console.log('ERR', e.message));
p.on('console', (m) => m.type() === 'error' && console.log('CONSOLE', m.text()));
await p.goto('http://127.0.0.1:5173/?fresh');
await p.waitForTimeout(700); await p.keyboard.press('Escape'); await p.waitForTimeout(3200);
await p.screenshot({ path: OUT + '/1-welcome.png' });
await p.getByRole('button', { name: 'Begin' }).click();
for (const t of [400, 900, 1300, 1650]) { await p.waitForTimeout(t - (t === 400 ? 0 : [0, 400, 900, 1300][[400, 900, 1300, 1650].indexOf(t)])); await p.screenshot({ path: `${OUT}/2-begin-${t}.png` }); }
await p.waitForTimeout(800);
await p.screenshot({ path: OUT + '/3-intro.png' });
await p.getByRole('button', { name: 'Someone else' }).click(); await p.waitForTimeout(300);
await p.screenshot({ path: OUT + '/4-someone.png' });
await p.getByRole('button', { name: 'Me', exact: true }).click(); await p.waitForTimeout(300);
await p.getByRole('button', { name: 'Me', exact: true }).click(); await p.waitForTimeout(1500);
await p.screenshot({ path: OUT + '/5-bust.png' });
await p.getByRole('button', { name: /Skip measuring/ }).click(); await p.waitForTimeout(1500);
await p.screenshot({ path: OUT + '/6-after-skip.png' });
await p.goto('http://127.0.0.1:5173/'); await p.waitForTimeout(700); await p.keyboard.press('Escape'); await p.waitForTimeout(1500);
await p.getByRole('button', { name: /Watch how it works/ }).click(); await p.waitForTimeout(800);
await p.screenshot({ path: OUT + '/7-tour.png' });
await b.close();
